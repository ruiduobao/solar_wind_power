def plot_debt_distribution(df, output_dir, log_path=None):  # Carbon debt distribution
    log_message("Plotting 5. Per-site carbon debt distribution...", log_path)  # Record progress
    plot_df = df[df["Total_Debt_tCO2"] > 0].copy()  # Filter invalid data
    plot_df["Log_Total_Debt"] = np.log10(plot_df["Total_Debt_tCO2"])  # Take logarithm
    plt.figure(figsize=(10, 6))  # Figure size
    sns.histplot(plot_df["Log_Total_Debt"], bins=50, kde=True, color="#d62728")  # Distribution plot
    plt.title("Distribution of Wind Carbon Debt per Site (Log10)", fontsize=16, fontweight="bold")  # Title
    plt.xlabel("Log10(Total Debt tCO2e)", fontsize=12)  # X axis
    plt.ylabel("Count of Wind Sites", fontsize=12)  # Y axis
    filename = "5_Hist_Debt_Distribution_Log10.png"  # Output figure name
    plt.savefig(os.path.join(output_dir, filename))  # Save figure
    plt.close()  # Close figure
    export_plot_data(plot_df["Log_Total_Debt"].describe(), filename, output_dir, log_path)  # Export chart data

def plot_debt_map(df, df_loc, output_dir, log_path=None):  # Carbon debt map distribution
    log_message("Plotting 6. Global carbon debt spatial distribution map...", log_path)  # Record progress
    if df_loc is None:  # If no location data
        log_message("Skipped: missing wind turbine location data; cannot plot the map.", log_path)  # Notice
        return  # Return
    df_m = df.merge(df_loc[["fid", "lon", "lat"]], on="fid", how="left")  # Merge longitude/latitude
    df_m = df_m[df_m["Total_Debt_tCO2"] > 0]  # Filter valid
    df_m = df_m.dropna(subset=["lon", "lat"])  # Drop records without coordinates
    try:  # Try to read world map
        world = gpd.read_file(WORLD_SHP)  # Read world map
    except Exception:  # Set to None on failure
        world = None  # No world map
    fig, ax = plt.subplots(figsize=(15, 8))  # Canvas
    if world is not None:  # Plot base map
        world.plot(ax=ax, color="#f0f0f0", edgecolor="white")  # World base map
    sc = ax.scatter(  # Scatter plot
        df_m["lon"], df_m["lat"],  # Coordinates
        c=df_m["Total_Debt_tCO2"],  # Color by carbon debt
        s=(df_m["Total_Debt_tCO2"] / df_m["Total_Debt_tCO2"].max()) * 50 + 2,  # Point size
        cmap="Reds",  # Color map
        norm=LogNorm(vmin=max(df_m["Total_Debt_tCO2"].quantile(0.05), 1e-6), vmax=df_m["Total_Debt_tCO2"].quantile(0.99)),  # Log color scale
        alpha=0.85,  # Transparency
        edgecolors="none"  # Edges
    )  # End of plotting
    plt.colorbar(sc, label="Total Carbon Debt (tCO2e)", fraction=0.02, pad=0.04)  # Color bar
    plt.title("Global Distribution of Wind Carbon Debt (2017+)", fontsize=16, fontweight="bold")  # Title
    plt.axis("off")  # Turn off axes
    filename = "6_Map_Wind_Carbon_Debt_2017plus.png"  # File name
    plt.savefig(os.path.join(output_dir, filename))  # Save figure
    plt.close()  # Close figure
    export_plot_data(df_m[["fid", "lon", "lat", "Total_Debt_tCO2"]], filename, output_dir, log_path)  # Export data

def plot_latitude_band(df, df_loc, output_dir, log_path=None):  # Latitude band analysis
    log_message("Plotting 7. Latitude band carbon debt statistics...", log_path)  # Record progress
    if df_loc is None:  # If no location data
        log_message("Skipped: missing wind turbine location data; cannot compute latitude bands.", log_path)  # Notice
        return  # Return
    df_m = df.merge(df_loc[["fid", "lat"]], on="fid", how="left")  # Merge latitude
    df_m = df_m.dropna(subset=["lat"])  # Drop records without latitude
    bins = list(range(-60, 95, 5))  # 5-degree bins
    df_m["lat_bin"] = pd.cut(df_m["lat"], bins=bins)  # Bin
    band_stats = df_m.groupby("lat_bin")["Total_Debt_tCO2"].sum() / 1e6  # MtCO2e
    band_stats = band_stats[band_stats > 0]  # Filter empty bins
    plt.figure(figsize=(12, 6))  # Canvas
    sns.barplot(x=band_stats.index.astype(str), y=band_stats.values, color="#d62728")  # Bar plot
    plt.xticks(rotation=90)  # Rotate X axis
    plt.title("Wind Carbon Debt by Latitude Band (2017+)", fontsize=16, fontweight="bold")  # Title
    plt.xlabel("Latitude Band (deg)")  # X axis
    plt.ylabel("Total Carbon Debt (MtCO2e)")  # Y axis
    filename = "7_Bar_Latitude_Band_TotalDebt_2017plus.png"  # Output name
    plt.tight_layout()  # Tight layout
    plt.savefig(os.path.join(output_dir, filename))  # Save figure
    plt.close()  # Close
    export_plot_data(band_stats, filename, output_dir, log_path)  # Export data

def plot_tech_intensity(df, df_mfg, output_dir, log_path=None):  # Technology-carbon intensity relationship plot
    log_message("Plotting 8. Technology-carbon intensity scatter plot...", log_path)  # Record progress
    if df_mfg is None or df_mfg.empty:  # If no manufacturing data
        log_message("Skipped: missing manufacturing carbon data; cannot plot the relationship.", log_path)  # Notice
        return  # Return
    df_p = df_mfg.copy()  # Copy manufacturing data
    df_p["fid"] = pd.to_numeric(df_p["fid"], errors="coerce").astype("Int64")  # Standardize fid
    df_p["Rated_Power_MW"] = pd.to_numeric(df_p.get("Rated_Power_MW", np.nan), errors="coerce")  # Rated power
    df_m = df.merge(df_p[["fid", "Rated_Power_MW"]], on="fid", how="left")  # Merge power
    df_m = df_m.dropna(subset=["Rated_Power_MW"])  # Filter missing
    df_m = df_m[df_m["Rated_Power_MW"] > 0]  # Filter non-positive values
    df_m["Debt_Intensity_tCO2_MW"] = df_m["Total_Debt_tCO2"] / df_m["Rated_Power_MW"]  # Compute intensity
    df_m["BubbleSize"] = (df_m["Total_Debt_tCO2"] / df_m["Total_Debt_tCO2"].max()) * 300 + 10  # Bubble size
    plt.figure(figsize=(12, 8))  # Canvas
    sc = plt.scatter(  # Scatter plot
        df_m["Rated_Power_MW"], df_m["Debt_Intensity_tCO2_MW"],  # Axes: rated power vs intensity
        c=df_m["installation_year"],  # Color by installation year
        s=df_m["BubbleSize"],  # Bubble size
        cmap="viridis",  # Color map
        alpha=0.8,  # Transparency
        edgecolors="k", linewidths=0.2  # Edges
    )  # End of plotting
    plt.colorbar(sc, label="Installation Year")  # Color bar
    plt.title("Rated Power vs Carbon Debt Intensity (2017+)", fontsize=16, fontweight="bold")  # Title
    plt.xlabel("Rated Power per Turbine (MW)")  # X axis
    plt.ylabel("Carbon Debt Intensity (tCO2e/MW)")  # Y axis
    filename = "8_Scatter_RatedPower_vs_DebtIntensity_2017plus.png"  # File name
    plt.savefig(os.path.join(output_dir, filename))  # Save figure
    plt.close()  # Close figure
    export_plot_data(df_m[["fid", "Rated_Power_MW", "Debt_Intensity_tCO2_MW", "installation_year", "Total_Debt_tCO2"]], filename, output_dir, log_path)  # Export data

