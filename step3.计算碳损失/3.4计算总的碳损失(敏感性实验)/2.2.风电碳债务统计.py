def ensure_dir(path):  # Create directory
    if not os.path.exists(path):  # Check whether the directory exists
        os.makedirs(path)  # Create directory

def log_message(message, log_path=None):  # Write log
    time_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")  # Current time
    full_message = f"[{time_str}] {message}"  # Compose log message
    print(full_message)  # Print to terminal
    if log_path:
        with open(log_path, "a", encoding="utf-8") as f:  # Open log file
            f.write(full_message + "\n")  # Write log

def export_plot_data(df, filename, output_dir, log_path=None):  # Export chart data
    csv_path = os.path.join(output_dir, filename.replace(".png", ".csv"))  # Output path
    df.to_csv(csv_path, index=True, encoding="utf-8-sig")  # Save CSV
    log_message(f"Chart data exported: {csv_path}", log_path)  # Record export info

def check_required_columns(df, cols, table_name, log_path=None):  # Check required columns
    missing = [c for c in cols if c not in df.columns]  # List of missing columns
    if missing:  # If any missing
        log_message(f"{table_name} missing columns: {missing}", log_path)  # Output log
        return False  # Return failure
    return True  # Return success

# ================= Data loading =================

def load_data(input_csv, log_path=None):  # Load wind total carbon debt data
    if not os.path.exists(input_csv):  # Check whether the input file exists
        log_message(f"Error: input file not found: {input_csv}", log_path)  # Output error
        return None  # Return None
    df = pd.read_csv(input_csv)  # Read input table
    log_message(f"Loaded data records: {len(df)}", log_path)  # Output record count
    required_ok = check_required_columns(df, ["fid", "Total_Debt_tCO2"], "Total carbon debt table", log_path)  # Check required columns
    if not required_ok:  # If required columns are missing
        return None  # Return None
    if "installation_year" not in df.columns and "year" in df.columns:  # If installation_year is missing
        df["installation_year"] = df["year"]  # Use year as a substitute
    if "installation_year" not in df.columns:  # If the year column still does not exist
        log_message("Error: missing installation_year/year field; cannot filter by year", log_path)  # Output error
        return None  # Return None
    df["installation_year"] = pd.to_numeric(df["installation_year"], errors="coerce")  # Convert to numeric
    df = df[df["installation_year"].notna()].copy()  # Drop records without year
    df["installation_year"] = df["installation_year"].astype(int)  # Convert to integer
    return df  # Return data

def load_shp_centroids(log_path=None):  # Load wind turbine buffer vector and compute centroid coordinates
    if not os.path.exists(WIND_SHP_PATH):  # Check whether the file exists
        log_message(f"Warning: wind turbine vector not found: {WIND_SHP_PATH}. Spatial distribution and latitude bands will be skipped.", log_path)  # Output warning
        return None  # Return None
    try:  # Try to read the vector
        gdf = gpd.read_file(WIND_SHP_PATH)  # Read vector
    except Exception as e:  # Read failed
        log_message(f"Failed to read wind turbine vector: {e}", log_path)  # Record error
        return None  # Return None
    # Standardize the fid column  # Column unification
    if "fid_1" in gdf.columns:  # If fid_1 exists
        gdf = gdf.rename(columns={"fid_1": "fid"})  # Rename to fid
    if "fid" not in gdf.columns:  # If fid still missing
        gdf["fid"] = gdf.index  # Use index as fid
    gdf["fid"] = pd.to_numeric(gdf["fid"], errors="coerce").astype("Int64")  # Convert to integer
    # Compute centroid coordinates  # Centroid computation
    try:  # Try to compute centroids
        gdf = gdf.to_crs(epsg=4326) if gdf.crs is not None else gdf  # Project to WGS84
        centroids = gdf.geometry.centroid  # Centroids
        df_loc = pd.DataFrame({  # Build location table
            "fid": gdf["fid"],  # fid column
            "lon": centroids.x,  # Longitude
            "lat": centroids.y,  # Latitude
            "country": gdf["COUNTRY"] if "COUNTRY" in gdf.columns else "Unknown"  # Country
        })  # DataFrame complete
        log_message(f"Wind turbine centroid coordinates extracted, records: {len(df_loc)}", log_path)  # Record success
        return df_loc  # Return location table
    except Exception as e:  # Centroid computation failed
        log_message(f"Failed to compute centroids: {e}", log_path)  # Record error
        return None  # Return None

