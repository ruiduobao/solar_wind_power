def process_scenario(scenario_name):
    """
    Process wind carbon debt statistics for a single scenario
    """
    print(f"\n>>> Processing statistics scenario: {scenario_name}")
    
    # Path setup
    input_csv = os.path.join(BASE_INPUT_DIR, scenario_name, "Wind_Total_Carbon_Debt_Result.csv")
    output_dir = os.path.join(BASE_INPUT_DIR, scenario_name)
    ensure_dir(output_dir)
    log_path = os.path.join(output_dir, "Wind_Debt_Stats_2017plus_Log.txt")
    
    mfg_csv = os.path.join(BASE_MFG_DIR, scenario_name, "Wind_Manufacturing_Carbon_Result.csv")
    
    if os.path.exists(log_path):
        os.remove(log_path)
    
    log_message(f"Scenario: {scenario_name}", log_path)
    log_message(f"Input file: {input_csv}", log_path)

    # Load data
    df = load_data(input_csv, log_path)
    if df is None or df.empty:
        log_message("Data is empty; skipping this scenario.", log_path)
        return

    # Filter by year
    df = df[df["installation_year"] >= START_YEAR].copy()
    log_message(f"Records from 2017 onwards: {len(df)}", log_path)
    
    # Data preprocessing
    df["Total_Debt_tCO2"] = df["Total_Debt_tCO2"].fillna(0)
    total_debt_mt = df["Total_Debt_tCO2"].sum() / 1e6
    log_message(f"Total wind carbon debt (2017+): {total_debt_mt:.4f} MtCO2e", log_path)

    # Plotting
    plot_country_ranking(df, output_dir, log_path)
    plot_annual_trend(df, output_dir, log_path)
    plot_component_pie(df, output_dir, log_path)
    plot_component_trend(df, output_dir, log_path)
    plot_debt_distribution(df, output_dir, log_path)
    
    # Load location data
    df_loc = load_shp_centroids(log_path)
    plot_debt_map(df, df_loc, output_dir, log_path)
    plot_latitude_band(df, df_loc, output_dir, log_path)
    
    # Read manufacturing data for the technology-intensity relationship
    df_mfg = pd.read_csv(mfg_csv) if os.path.exists(mfg_csv) else None
    plot_tech_intensity(df, df_mfg, output_dir, log_path)
    
    log_message("All figures and data generated.", log_path)

def main():
    scenarios = ["乐观场景", "标准场景", "悲观场景"]
    for scenario in scenarios:
        process_scenario(scenario)

if __name__ == "__main__":
    main()
